// Largest of Two Numbers

let num1 = 45;
let num2 = 60;

console.log("Number 1 :", num1);
console.log("Number 2 :", num2);

if (num1 > num2) {
    console.log(num1 + " is the largest number");
} else if (num2 > num1) {
    console.log(num2 + " is the largest number");
} else {
    console.log("Both numbers are equal");
}